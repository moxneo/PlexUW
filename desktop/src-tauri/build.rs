// Custom commands are declared in the app manifest and granted per window in
// capabilities/default.json (§6a M3).
fn main() {
    // Sentinel LOW-16: the fixture-only screenshot command is declared (and so gets a
    // permission) only when building with --features mockplex.
    let mock = std::env::var_os("CARGO_FEATURE_MOCKPLEX").is_some();
    let base: &[&str] = &[
        "win_minimize", "win_toggle_maximize", "win_close", "win_toggle_fullscreen", "win_is_fullscreen", "win_state",
        "source_get", "auth_start", "auth_cancel", "servers_list", "server_connect", "manual_probe",
        "sign_out", "prefs_get", "prefs_set", "ai_key_set", "ai_key_has",
        "browse_home", "browse_section", "browse_section_hubs", "browse_facet", "browse_collections", "browse_collection",
        "browse_item", "browse_children", "browse_search", "play_start", "opaque_get", "playback_stop", "manual_confirm", "ai_migration_failed", "browse_letters", "version_pick",
        "browse_person", "browse_related", "account_me", "mark_watched",
        "watchlist_list", "watchlist_add", "watchlist_remove",
    ];
    let mut cmds: Vec<&'static str> = base.to_vec();
    if mock { cmds.push("shot_id"); }
    // fu7h LOW-A': tauri-build writes permissions/autogenerated/<cmd>.toml but never removes stale
    // ones, so a previous mockplex build left shot_id.toml behind and release builds then carried the
    // inert allow-/deny-shot-id permission ids. Release builds drop that one generated file first.
    if !mock {
        let stale = std::path::Path::new("permissions/autogenerated/shot_id.toml");
        if stale.exists() { std::fs::remove_file(stale).expect("remove stale mock-only permission"); }
    }
    // use_demo is no longer a command. tauri-build does not delete a stale permission file.
    let stale_demo = std::path::Path::new("permissions/autogenerated/use_demo.toml");
    if stale_demo.exists() { std::fs::remove_file(stale_demo).expect("remove stale use_demo permission"); }
    println!("cargo:rerun-if-changed=permissions/autogenerated/use_demo.toml");
    // Re-run (and so re-clean) whenever a mock build recreates the file.
    println!("cargo:rerun-if-changed=permissions/autogenerated/shot_id.toml");
    // AppManifest wants a 'static slice; leaking once in a build script is fine.
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(tauri_build::AppManifest::new().commands(Box::leak(cmds.into_boxed_slice()))))
    .expect("tauri build");
}
